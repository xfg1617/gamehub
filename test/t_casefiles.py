"""Case Files solo (v2, Nov 2026): rooms are searched by tapping objects (most hold nothing), records are read in a
cabinet and the important lines are marked by hand, suspects are shown cards from the board. Then a wrong and a right
accusation. Also: Solo is offered on the first screen."""
import sys; sys.path.insert(0, 'test')
from tlib import *
fails = []
def check(ok, what): print('PASS' if ok else 'FAIL', what); fails.append(what) if not ok else None
E = 'GAME_MODS.casefiles.engine'
with sync_playwright() as p:
    br = launch(p); pg = open_page(br, 1440, 900)
    pg.evaluate("openGame('casefiles')"); pg.wait_for_timeout(500)
    if pg.query_selector('[data-mode="solo"]'): pg.click('[data-mode="solo"]')
    pg.evaluate("(() => { const b = [...document.querySelectorAll('#gs-body button')].find(x => /^\\s*(start|play)/i.test(x.textContent)); b && b.click(); })()")
    pg.wait_for_timeout(800)
    check('The Harbor Pearl' in pg.inner_text('#cf-view') and pg.evaluate(f"{E}.G.role") == 'both', 'solo: the case opens and you hold both halves')
    # where each clue sits: (room, object index)
    where = pg.evaluate(f"(() => {{ const C = {E}.G.C, out = {{}}; Object.entries(C.ROOMS).forEach(([r, o]) => o.items.forEach((it, i) => {{ if (it.c) out[it.c] = [r, i]; }})); return out; }})()")
    pg.click('[data-tab="inv"]')
    # tap an ordinary object: it can be pinned too, with your own note, and looks just like a clue on the board
    pg.click('[data-room="library"]'); pg.click('.cf-it[data-item="0"]'); pg.wait_for_timeout(100)
    check('Nothing useful here' not in pg.inner_text('#cf-view') and pg.query_selector('[data-pin="it:library:0"]'), 'an ordinary object can be pinned (no "nothing useful" give-away)')
    pg.fill('[data-note="it:library:0"]', 'odd?'); pg.click('[data-pin="it:library:0"]'); pg.wait_for_timeout(60)
    check(pg.evaluate(f"{E}.G.pins.some(p => p.id === 'it:library:0' && p.note === 'odd?')"), 'the decoy goes on the board with its note')
    pg.evaluate(f"{E}.G.S.act({{ s: 0, t: 'unpin', id: 'it:library:0' }})")
    check('searched' not in pg.inner_text('#cf-view').lower(), 'no "x of y searched" counters')
    for cid in ['a_prints', 'a_path', 'a_cart', 'a_shoes', 'a_card', 'a_pills']:
        r, i = where[cid]; pg.click(f'[data-room="{r}"]'); pg.click(f'.cf-it[data-item="{i}"]'); pg.wait_for_timeout(60)
        if pg.query_selector(f'[data-pin="{cid}"]'): pg.click(f'[data-pin="{cid}"]')
    pg.screenshot(path='test/shots/cf_scene.png')
    check(pg.evaluate(f"{E}.G.pins.length") == 6, f'6 scene clues found by tapping objects and pinned ({pg.evaluate(f"{E}.G.pins.length")})')
    # records: open drawers, read documents, mark lines
    pg.click('[data-view="B"]'); pg.click('[data-tab="inv"]')
    drawer = pg.evaluate(f"(() => {{ const out = {{}}; {E}.G.C.DRAWERS.forEach((d, i) => d.docs.forEach((id) => out[id] = i)); return out; }})()")
    def read(doc, rows):
        pg.click(f'[data-drawer="{drawer[doc]}"]'); pg.click(f'[data-doc="{doc}"]')
        for rw in rows: pg.click(f'.cf-row[data-row="{rw}"]')
        if doc == 'b_doors': pg.fill('[data-note="b_doors"]', 'who opened 204 from inside?')
        pg.click(f'[data-pin="{doc}"]'); pg.wait_for_timeout(60)
    read('b_doors', [4, 5]); read('b_house', [1, 3]); read('b_phone', [2, 3])
    pg.click('[data-drawer="0"]'); pg.click('[data-doc="b_guests"]')
    check(pg.evaluate("document.querySelectorAll('.cf-row.mk').length") == 0, 'nothing is highlighted for you: you mark lines yourself')
    pg.click('[data-drawer="4"]'); pg.click('[data-doc="b_bell"]'); pg.screenshot(path='test/shots/cf_records.png')
    for d, doc in [(2, 'b_bar'), (4, 'b_phone'), (3, 'b_house'), (0, 'b_doors')]:
        pg.click(f'[data-drawer="{d}"]'); pg.click(f'[data-doc="{doc}"]'); pg.locator('.cf-sheet').screenshot(path=f'test/shots/cf_paper_{doc}.png')
    pg.click('[data-tab="board"]')
    btxt = pg.inner_text('#cf-cork'); print('   board door log card:', pg.inner_text('.cf-pin[data-p="b_doors"]').replace('\n', ' | '))
    check('who opened 204' in btxt and 'opened from INSIDE' in btxt and 'guest card · E. Cross' not in btxt, 'the board card shows only the lines you marked')
    # interviews: ask questions, then show cards from the board
    pg.click('[data-view="A"]'); pg.click('[data-tab="sus"]'); pg.click('[data-sus="marcus"]')
    pg.click('[data-ask="0"]')
    pg.click('[data-showmenu]'); pg.click('[data-show="b_doors"]'); pg.wait_for_timeout(80)
    pg.click('[data-showmenu]'); pg.click('[data-show="a_path"]'); pg.wait_for_timeout(80)
    t = pg.inner_text('#cf-view')
    check('stepped out for some air' in t, 'showing Marcus the door log gets a real reaction')
    check('Can I go back to bed' in t, 'showing him something unrelated gets a shrug')
    pg.screenshot(path='test/shots/cf_interview.png')
    pg.click('[data-tab="board"]')
    def tap(id): pg.click(f'.cf-pin[data-p="{id}"]', position={'x': 60, 'y': 30})
    tap('b_doors'); tap('a_shoes')
    check(pg.evaluate(f"{E}.G.strings.length") == 1, 'tapping two cards ties them with string')
    pg.fill('#cf-notetxt', 'Marcus lied: out 9:18, back 9:43'); pg.click('[data-addnote]')
    pg.screenshot(path='test/shots/cf_board.png')
    pg.click('[data-tab="acc"]')
    pg.click('[data-acc="who"][data-v="ethan"]'); pg.click('[data-acc="how"][data-v="spare"]'); pg.click('[data-acc="why"][data-v="debt"]')
    for k in ['b_doors', 'a_shoes', 'b_phone']: pg.click(f'[data-ev="{k}"]')
    pg.click('[data-propose]'); pg.wait_for_timeout(300)
    check(pg.evaluate(f"{E}.G.tries") == 1, 'a wrong accusation costs a star')
    pg.click('[data-acc="who"][data-v="marcus"]'); pg.click('[data-propose]'); pg.wait_for_timeout(500)
    check(pg.evaluate(f"{E}.G.solved") and 'SOLVED' in pg.inner_text('#cf-view'), 'the right accusation closes the case')
    pg.screenshot(path='test/shots/cf_solved.png', full_page=True)
    check(not pg.errs, 'no page errors ' + str(pg.errs[:2]))
    m = open_page(br, 390, 844, mobile=True); m.evaluate("openGame('casefiles')"); m.wait_for_timeout(500)
    m.evaluate("(() => { const b = [...document.querySelectorAll('#gs-body button')].find(x => /^\\s*(start|play)/i.test(x.textContent)); b && b.click(); })()"); m.wait_for_timeout(600)
    m.click('[data-tab="inv"]'); m.click('[data-room="floor2"]'); m.click('.cf-it[data-item="0"]')
    w = m.evaluate("document.documentElement.scrollWidth"); check(w <= 392, f'phone: no sideways scrolling ({w}px)'); m.screenshot(path='test/shots/cf_phone.png', full_page=True)
print('ALL PASS' if not fails else f'FAILED: {fails}')
