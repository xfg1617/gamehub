"""Friends (stand-in service): look a player up by name, open their card (no email), send a friend request, the other
player sees it (badge + toast) and accepts, friend chat both ways with a pop-up for the receiver (emails/phone numbers
hidden), a room invite sent from the room arrives as a Join button that drops the friend into the room, tapping a name
in room chat opens that player's card, and removing a friend."""
import sys; sys.path.insert(0, 'test')
from nplib import *
with sync_playwright() as p:
    A, B = players(p, 2)
    for pg in (A, B): pg.set_viewport_size({'width': 1280, 'height': 900})
    bname = B.evaluate("NET.me.name"); aname = A.evaluate("NET.me.name")
    A.evaluate("navigateTo('friends')"); A.wait_for_timeout(600)
    A.fill('#fr-q', bname[:5]); A.click('#fr-go'); A.wait_for_timeout(800)
    found = A.evaluate("[...document.querySelectorAll('#fr-results .fr-row')].map(e => e.innerText)")
    check(any(bname in f for f in found), f'look-up finds {bname}')
    A.click('#fr-results [data-card]'); A.wait_for_timeout(800)
    card = A.inner_text('#pcard-modal')
    check(bname in card and '@' not in card and 'Add friend' in card, 'the player card shows name + rankings, no email, and Add friend')
    A.screenshot(path='test/shots/fr_card.png')
    A.click('#pcard-modal [data-act="add"]'); A.wait_for_timeout(1500)
    check('request sent' in A.inner_text('#pcard-modal').lower(), 'the request is sent')
    A.evaluate("document.getElementById('pcard-modal').classList.add('hidden')")
    B.wait_for_timeout(2500)
    check(B.evaluate("!document.getElementById('nav-friends-badge').classList.contains('hidden')"), 'the other player gets a badge on Friends')
    B.evaluate("navigateTo('friends')"); B.wait_for_timeout(700)
    aname = B.evaluate("(id) => NET.profileOf(id).then(p => p.name)", A.evaluate("NET.me.id"))
    print('   B list:', B.inner_text('#fr-list').replace('\n', ' / ')[:160], '| A is', aname)
    check(aname in B.inner_text('#fr-list') and B.query_selector('#fr-list [data-acc]') is not None, 'they see the request with Accept')
    B.click('#fr-list [data-acc]'); B.wait_for_timeout(2000)
    A.evaluate("navigateTo('play', true); navigateTo('friends')"); A.wait_for_timeout(1200)
    check(bname in A.inner_text('#fr-list') and 'ONLINE' in A.inner_text('#fr-list'), 'both are friends, shown as online')
    # chat
    A.evaluate("openFriendChat(NET.me && FR.list.friends[0].id)"); A.wait_for_timeout(800)
    B.evaluate("navigateTo('play', true)"); B.wait_for_timeout(400)
    A.fill('#fr-chatwin input', 'hey! my email is someone@gmail.com'); A.press('#fr-chatwin input', 'Enter'); A.wait_for_timeout(2000)
    pops = B.evaluate("[...document.querySelectorAll('.chat-pop')].map(e => e.innerText).join(' | ')")
    print('   B pop-up:', pops[:120])
    check('hey!' in pops and 'gmail' not in pops and 'FRIEND' in pops, 'the friend gets a pop-up; the email is hidden')
    B.evaluate("openFriendChat(FR.list.friends[0].id)"); B.wait_for_timeout(1200)
    check('[email hidden]' in B.inner_text('#fr-chatwin'), 'the message shows with the email hidden')
    B.fill('#fr-chatwin input', 'hi back'); B.press('#fr-chatwin input', 'Enter'); A.wait_for_timeout(2000)
    check('hi back' in A.inner_text('#fr-chatwin'), 'replies arrive in the open chat')
    B.screenshot(path='test/shots/fr_chat.png')
    # invite from a room
    code = open_table(A, 'tictactoe', 'room')
    A.click('#np-finv'); A.wait_for_timeout(500); A.click('#finv-modal [data-inv]'); A.wait_for_timeout(1500)
    check('Sent' in A.inner_text('#finv-modal'), 'Invite friends sends the invite'); A.click('#finv-x')
    B.evaluate("navigateTo('play', true); navigateTo('friends')"); B.wait_for_timeout(800)
    B.evaluate("openFriendChat(FR.list.friends[0].id)"); B.wait_for_timeout(1500)
    check(B.query_selector('#fr-chatwin [data-join]') is not None, 'the room invite arrives with a Join button')
    B.click('#fr-chatwin [data-join]'); B.wait_for_timeout(3500)
    check(A.evaluate("document.querySelectorAll('#np-lob .np-seat.on').length") == 2, 'Join drops the friend into the room')
    # a name in room chat opens the card
    B.fill('#np-chat input', 'ready?'); B.press('#np-chat input', 'Enter'); A.wait_for_timeout(1500)
    A.click('#np-chat [data-uid]'); A.wait_for_timeout(1000)
    check(bname in A.inner_text('#pcard-modal') and 'FRIEND' in A.inner_text('#pcard-modal'), 'tapping a name in chat opens their player card')
    A.click('#pcard-modal [data-act="rm"]'); A.wait_for_timeout(1500)
    check('Add friend' in A.inner_text('#pcard-modal'), 'removing a friend works')
    done(A, B)
