"""The Ranked Match banner on the home page lets you choose which game to play ranked.
Online: a picker of every ranked game -> that game's setup with "Online · quick match" chosen (2 players) -> two
players who pick the same game get paired. Offline: the picker says ranked needs online and opens the game vs the computer."""
import sys, os; sys.path.insert(0, 'test')
from nplib import *
with sync_playwright() as p:
    A, B = players(p, 2)
    A.set_viewport_size({'width': 1280, 'height': 900}); A.wait_for_timeout(1200)
    check(A.evaluate("document.querySelectorAll('#hero-screen .hero-tile').length") >= 20, 'the banner screen shows the ranked games scrolling past')
    print('   banner label:', A.evaluate("document.getElementById('screen-score').parentElement.textContent"))
    A.screenshot(path='test/shots/ranked_banner.png', full_page=False)
    A.click('.hp-side .btn-amber'); A.wait_for_timeout(600)
    names = A.evaluate("[...document.querySelectorAll('[data-rk] .nm')].map(e => e.textContent)")
    print('   picker:', names)
    check(len(names) >= 10 and 'Chess' in names and 'Sea Battle' in names and 'Pool' in names, 'clicking the banner offers every ranked game')
    A.click('[data-rk="c4"]'); A.wait_for_timeout(500)
    A.screenshot(path='test/shots/ranked_picker.png')
    check('Four-in-a-Row' in A.inner_text('#rk-go'), 'the button names the chosen game')
    A.click('#rk-go'); A.wait_for_timeout(1500)
    check(A.query_selector('#np-lob') is not None and 'SEARCHING' in A.inner_text('#np-lob'), 'it goes straight into matchmaking (no extra screen)')
    B.click('.hp-side .btn-amber'); B.wait_for_timeout(500); B.click('[data-rk="c4"]'); B.click('#rk-go'); B.wait_for_timeout(800)
    A.wait_for_timeout(5000)
    bar = A.evaluate("(document.querySelector('.np-bar') || {}).textContent || ''")
    print('   A table bar:', bar[:80])
    check('RANKED' in bar, 'two players who chose the same game are paired in a ranked match')
    closeA = A.evaluate("closeActiveGame && 1"); B.evaluate("closeActiveGame && 1")
    # 3-player games are set to 2 players so the quick match is ranked
    B.evaluate("navigateTo('play', true)"); B.wait_for_timeout(500)
    B.click('.hp-side .btn-amber'); B.wait_for_timeout(500); B.click('[data-rk="kittens"]'); B.click('#rk-go'); B.wait_for_timeout(1800)
    check(B.evaluate("document.querySelectorAll('#np-lob .np-seat').length") == 2, 'Kaboom Cats looks for a 2-player (ranked) table')
    B.evaluate("navigateTo('play', true)"); B.wait_for_timeout(500)
    B.evaluate("closeActiveGame()"); B.evaluate("navigateTo('play', true)"); B.wait_for_timeout(400)
    B.click('.hp-side .btn-amber'); B.wait_for_timeout(500); B.click('[data-rk="chess"]'); B.click('#rk-go'); B.wait_for_timeout(2500)
    check('WAITING FOR A PLAYER' in B.inner_text('#game-root') or 'FINDING' in B.inner_text('#game-root'), 'Chess goes straight into ranked matchmaking')
    B.evaluate("navigateTo('play', true)"); B.wait_for_timeout(500)
    B.evaluate("closeActiveGame()"); B.evaluate("navigateTo('play', true)"); B.wait_for_timeout(400)
    B.click('.hp-side .btn-amber'); B.wait_for_timeout(500); B.click('[data-rk="navalnet"]'); B.click('#rk-go'); B.wait_for_timeout(1800)
    check(B.query_selector('#np-lob') is not None and 'SEARCHING' in B.inner_text('#np-lob'), 'Sea Battle goes straight into its online quick match')
    # offline
    br = launch(p); C = br.new_page(viewport={'width': 1280, 'height': 900}); errs = []; C.on('pageerror', lambda e: errs.append(str(e)))
    C.goto('file://' + os.path.abspath('dist/gamehub.html')); C.wait_for_timeout(1500)
    C.click('.hp-side .btn-amber'); C.wait_for_timeout(500)
    check('online play' in C.inner_text('#rp-body') and C.inner_text('[data-rk="pool"] .pl') == 'vs Computer', 'offline: the picker explains ranked needs online')
    C.click('[data-rk="navalnet"]'); C.click('#rk-go'); C.wait_for_timeout(800)
    check(C.query_selector('#su-go') is not None or C.query_selector('#view-naval:not(.hidden)') is not None, 'offline: Sea Battle opens vs the computer')
    check(not errs, 'no page errors offline ' + str(errs[:2]))
    done(A, B)
